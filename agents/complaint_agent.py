"""Intake / classification agent: category, priority, summary and a formal draft.

analyze_complaint(description, location, category_hint=None, use_llm=True) -> ComplaintAnalysis
Works fully offline. If ANTHROPIC_API_KEY is set, ONE LLM call (services.llm) adds:
  * a category second opinion, used only when the user gave no category and keyword confidence is low;
  * a safety check that may raise the rule-based priority by at most one step (never lower it);
  * a clearer one-line summary and a polished formal letter.
Every LLM output is validated; anything invalid falls back to the deterministic result.
"""
import re

import config
from models import trace_step
from services import classifier, llm
from services.department_directory import get_department
from services.validation import normalize_text

AGENT = "Intake Agent"
LLM_CATEGORY_BELOW = 0.6      # ask the LLM to arbitrate only when keyword confidence is below this


def build_summary(category: str, location: str, description: str, priority: str) -> str:
    first = re.split(r"(?<=[.!?])\s+", description.strip())[0]
    first = first[:140].rstrip(" ,;:")
    return f"{config.label(category)} at {location} ({priority} priority): {first}"


def build_draft(description: str, location: str, category: str, priority: str, reason: str) -> str:
    dept = get_department(category)["name"]
    return (
        f"To,\nThe Officer-in-Charge\n{dept}\n\n"
        f"Subject: {config.label(category)} at {location}: request for inspection and action\n\n"
        "Respected Sir/Madam,\n\n"
        "I wish to bring the following civic issue to your kind attention.\n\n"
        f"Location: {location}\n"
        f"Issue type: {config.label(category)}\n"
        f"Assessed priority: {priority}\n\n"
        f"Details: {description.strip()}\n\n"
        "I request you to inspect the site, take the necessary corrective action at the earliest, "
        "and share the expected timeline for resolution.\n\n"
        "Thank you for your attention.\n\nYours sincerely,\nA concerned citizen\n\n"
        "[DRAFT generated by CivicFix AI. Review and edit before use. Not submitted anywhere.]"
    )


def llm_enrich(description: str, location: str, category: str, priority: str, template: str,
               allow_category: bool) -> tuple[dict | None, str]:
    """One validated LLM call. Returns ``(fields | None, note)``; never raises."""
    if not llm.available():
        return None, "No API key configured; deterministic template used."
    prompt = (
        "Review this civic complaint.\n"
        f"Allowed categories: {', '.join(config.CATEGORIES)}. Allowed priorities: {', '.join(config.PRIORITIES)}.\n"
        f"Rule-based result: category={category}, priority={priority}.\n"
        "Return JSON with keys:\n"
        '  "category": best category from the allowed list,\n'
        '  "priority": your priority (be conservative; raise only for real safety/health risk),\n'
        '  "priority_reason": one short sentence,\n'
        '  "summary": one clear sentence under 160 characters,\n'
        '  "draft": a concise, polite, formal letter to the department (plain text, keep every fact, '
        "written for the category and priority you chose; must mention the location exactly as given).\n\n"
        f"Location: {llm.wrap(location)}\nDetails: {llm.wrap(description)}\n\nCurrent draft:\n{llm.wrap(template)}"
    )
    obj, note = llm.complete_json(prompt, max_tokens=900)
    if obj is None:
        return None, f"{note} Template used."
    out: dict = {}
    cat = str(obj.get("category", "")).strip().lower()
    out["raw_category"] = cat
    out["raw_priority"] = str(obj.get("priority", "")).strip().capitalize()
    out["category"] = cat if allow_category and cat in config.CATEGORIES else None
    pri = str(obj.get("priority", "")).strip().capitalize()
    if pri in config.PRIORITIES:
        gap = config.PRIORITIES.index(pri) - config.PRIORITIES.index(priority)
        out["priority"] = pri if gap == 1 else None          # may raise by exactly one step, never lower
    out["priority_reason"] = str(obj.get("priority_reason", "")).strip()[:200]
    summary = " ".join(str(obj.get("summary", "")).split())
    out["summary"] = summary if 15 <= len(summary) <= 200 else None
    text = str(obj.get("draft", "")).strip()
    ok = 80 <= len(text) <= 3000 and location.lower() in text.lower()
    out["draft"] = (text + "\n\n[DRAFT polished by an LLM. Review and edit before use. Not submitted anywhere.]"
                    if ok else None)
    return out, f"LLM review passed validation (model {config.LLM_MODEL})."


def _confidence_label(confidence: float, source: str) -> str:
    if source == "user":
        return "set by user"
    return "high" if confidence >= 0.75 else "medium" if confidence >= 0.5 else "low"


def validate_analysis(a: dict) -> None:
    """Raise ValueError if the analysis is not safe to pass to the next component."""
    if a.get("category") not in config.CATEGORIES:
        raise ValueError(f"invalid category {a.get('category')!r}")
    if a.get("priority") not in config.PRIORITIES:
        raise ValueError(f"invalid priority {a.get('priority')!r}")
    if not isinstance(a.get("confidence"), (int, float)) or not 0 <= a["confidence"] <= 1:
        raise ValueError("confidence must be between 0 and 1")
    for field in ("summary", "draft", "description", "location"):
        if not str(a.get(field, "")).strip():
            raise ValueError(f"empty field {field!r}")


def analyze_complaint(description: str, location: str, category_hint=None, use_llm: bool = True) -> dict:
    trace = []
    description, location = normalize_text(description, multiline=True), normalize_text(location)
    if not description or not location:
        raise ValueError("description and location are required")
    if len(description) > config.DESCRIPTION_MAX or len(location) > config.LOCATION_MAX:
        raise ValueError("description or location exceeds the maximum length")
    cls = classifier.classify(f"{description} {location}")
    hint = category_hint if category_hint in config.CATEGORIES else None
    confidence = cls["confidence"]
    if hint:
        category, source = hint, "user"
        note = (f" The classifier suggested '{cls['category']}' (confidence {cls['confidence']})."
                if cls["category"] != hint else " The classifier agrees.")
        trace.append(trace_step(AGENT, "classify", f"Category = {hint}", "User selected the category." + note,
                                "User choice respected (human override of the agent)."))
    else:
        category, source = cls["category"], "classifier"
        kws = ", ".join(cls["matched_keywords"][:6]) or "none"
        trace.append(trace_step(AGENT, "classify", f"Category = {category}",
                                f"Keyword scoring {cls['scores']}; matched: {kws}.",
                                f"Confidence {cls['confidence']}."
                                + (" Low confidence, so filed as 'other'." if category == "other" else "")))

    pr = classifier.assess_priority(description, category)
    priority, reason, score = pr["priority"], "; ".join(pr["reasons"]), pr["score"]
    draft = build_draft(description, location, category, priority, reason)
    summary = build_summary(category, location, description, priority)
    text_source, draft_note = "template", "Deterministic template (AI polishing not requested)."

    if use_llm:
        arbitrate = source == "classifier" and cls["confidence"] < LLM_CATEGORY_BELOW
        fields, draft_note = llm_enrich(description, location, category, priority, draft, arbitrate)
        if fields:
            if fields["category"] and fields["category"] != category:
                trace.append(trace_step(AGENT, "llm_classify", f"Category = {fields['category']}",
                                        f"Keyword confidence {cls['confidence']} was low; LLM second opinion "
                                        f"replaced '{category}'.", "Category updated; the citizen can still change it."))
                category, source, confidence = fields["category"], "classifier", max(cls["confidence"], 0.6)
                pr = classifier.assess_priority(description, category)
                priority, reason, score = pr["priority"], "; ".join(pr["reasons"]), pr["score"]
            if fields["priority"]:
                why = fields["priority_reason"] or "LLM flagged a safety or health risk"
                trace.append(trace_step(AGENT, "llm_priority_review", f"Priority raised to {fields['priority']}",
                                        why, f"Rule-based priority was {priority}; raised one step (never lowered)."))
                priority, reason = fields["priority"], f"{reason}; LLM review: {why}"
            draft = build_draft(description, location, category, priority, reason)
            summary = build_summary(category, location, description, priority)
            if fields["summary"]:
                summary = f"{config.label(category)} at {location} ({priority} priority): {fields['summary']}"[:300]
            consistent = fields["raw_category"] == category and fields["raw_priority"] == priority
            if fields["draft"] and consistent:       # the letter was written for exactly the final category/priority
                draft, text_source = fields["draft"], "llm"
            elif fields["draft"]:
                draft_note += " Template kept: the LLM letter did not match the final category/priority."
    trace.append(trace_step(AGENT, "assess_priority", f"Priority = {priority}", reason, f"Rule score {score}."))
    trace.append(trace_step(AGENT, "draft", "Formal complaint drafted", draft_note,
                            "Draft awaits human review; nothing has been sent."))
    analysis = {"description": description.strip(), "location": location.strip(), "category": category,
                "category_source": source, "confidence": confidence, "priority": priority,
                "priority_score": score, "priority_reason": reason, "summary": summary,
                "draft": draft, "text_source": text_source,
                "confidence_label": _confidence_label(confidence, source),
                "confidence_note": "Keyword-based estimate (share of keyword evidence), not a probability.",
                "trace": trace}
    validate_analysis(analysis)
    return analysis